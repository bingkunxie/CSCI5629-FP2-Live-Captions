        public static string Get(string text, bool chinese)
        {
            if (string.IsNullOrEmpty(text)) return text ?? "";
            if (chinese) return Chinese.TryGetValue(text, out var value) ? value : text;
            foreach (var pair in Chinese) if (pair.Value == text) return pair.Key;
            return text;
        }
        public static string Status(string text,bool chinese)
        {
            if(string.IsNullOrEmpty(text))return "";
            var parts=text.Split(new[]{" | "},System.StringSplitOptions.None);
            for(int i=0;i<parts.Length;i++)parts[i]=Get(parts[i],chinese);
            return string.Join(" | ",parts);
        }
